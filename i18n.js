const cache = new Map();
export function translateText(s, lang) {
  if (!lang || lang === 'en') return s;
  const core = s.trim();
  if (!core) return s;
  const key = lang + '\u0000' + core;
  let out = cache.get(key);
  if (out === undefined) {
    out = DICT[lang]?.[core];
    // "A · B · C" is translated piece by piece
    if (out === undefined && core.includes(' · ')) out = core.split(' · ').map((p) => translateText(p, lang)).join(' · ');
    if (out === undefined) {
      for (const [re, tpl] of PATTERNS) {
        const m = core.match(re);
        if (m && tpl[lang]) { out = tpl[lang].replace(/\$(\d)/g, (_, i) => translateText(m[Number(i)] ?? '', lang)); break; }
      }
    }
    if (out === undefined) out = core;
    cache.set(key, out);
  }
  return s.replace(core, () => out);
}
