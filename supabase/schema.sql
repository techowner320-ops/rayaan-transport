-- ============ Part 4: erase all business data (administrator only) ============
-- Removes every business record and restarts numbering at 1. Keeps logins, profiles and company settings.
create function public.erase_all_data() returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then
    raise exception 'Only the administrator can erase data';
  end if;
  truncate table public.payments, public.expenses, public.fuel, public.maintenance,
    public.missions, public.vehicles, public.clients restart identity;
end $$;
revoke execute on function public.erase_all_data() from public, anon;
grant execute on function public.erase_all_data() to authenticated;

-- ============ Part 5: money in several currencies ============
-- Every money record carries its own currency (USD, GBP or SLSH = Somaliland shilling).
-- settings.rates holds how many units of each currency equal 1 USD; reports add everything up
-- in the company currency (settings.currency) using those rates.
alter table public.settings add column rates jsonb not null default '{"USD": 1, "GBP": 0.78, "SLSH": 9000}'::jsonb;

alter table public.missions    add column currency text not null default 'USD' check (currency in ('USD', 'GBP', 'SLSH'));
alter table public.fuel        add column currency text not null default 'USD' check (currency in ('USD', 'GBP', 'SLSH'));
alter table public.maintenance add column currency text not null default 'USD' check (currency in ('USD', 'GBP', 'SLSH'));
alter table public.expenses    add column currency text not null default 'USD' check (currency in ('USD', 'GBP', 'SLSH'));
alter table public.payments    add column currency text not null default 'USD' check (currency in ('USD', 'GBP', 'SLSH'));

create function public.to_base(p_amount numeric, p_cur text) returns numeric
language sql stable set search_path = '' as $$
  select coalesce(
    (select p_amount / coalesce((s.rates ->> p_cur)::numeric, 1) * coalesce((s.rates ->> s.currency)::numeric, 1)
       from public.settings s where s.id = 1),
    p_amount)
$$;
revoke execute on function public.to_base(numeric, text) from public, anon;
grant execute on function public.to_base(numeric, text) to authenticated;

