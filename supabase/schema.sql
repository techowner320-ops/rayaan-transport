      select to_char(d, 'YYYY-MM') as month,
        (select coalesce(sum(public.to_base(amount, currency)), 0) from public.missions where status <> 'Cancelled' and date_trunc('month', start_date) = d) as revenue,
        (select coalesce(sum(public.to_base(cost, currency)), 0) from public.fuel where date_trunc('month', date) = d)
          + (select coalesce(sum(public.to_base(cost, currency)), 0) from public.maintenance where date_trunc('month', date) = d)
          + (select coalesce(sum(public.to_base(amount, currency)), 0) from public.expenses where date_trunc('month', date) = d) as costs
      from generate_series(date_trunc('month', current_date) - interval '5 months', date_trunc('month', current_date), interval '1 month') d
    ) m)
  )
$$;

