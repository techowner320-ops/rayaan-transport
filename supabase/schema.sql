-- ============ Audit: who created / last edited each record ============
create function public.set_audit() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  who text := (select coalesce(nullif(full_name, ''), email) from public.profiles where id = auth.uid());
begin
  if tg_op = 'INSERT' then
    new.created_at := now(); new.created_by := who;
    new.updated_at := null; new.updated_by := null;
  else
    new.created_at := old.created_at; new.created_by := old.created_by;
    new.updated_at := now(); new.updated_by := who;
  end if;
  return new;
end $$;
revoke execute on function public.set_audit() from public, anon, authenticated;

-- ============ Security: approved staff only; only admins delete ============
do $$
declare t text;
begin
  foreach t in array array['vehicles', 'clients', 'missions', 'fuel', 'maintenance', 'expenses', 'payments'] loop
    execute format('create trigger %I before insert or update on public.%I for each row execute function public.set_audit()', t || '_audit', t);
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "members read" on public.%I for select to authenticated using ((select public.is_member()))', t);
    execute format('create policy "members add" on public.%I for insert to authenticated with check ((select public.is_member()))', t);
    execute format('create policy "members edit" on public.%I for update to authenticated using ((select public.is_member())) with check ((select public.is_member()))', t);
    execute format('create policy "admins delete" on public.%I for delete to authenticated using ((select public.is_admin()))', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

-- ============ Vehicle status follows its missions ============
-- An Ongoing mission marks the vehicle Working; when none are ongoing it is
-- Available again. Vehicles Under Maintenance are left alone.
create function public.sync_vehicle_status() returns trigger
language plpgsql set search_path = '' as $$
declare
  vid bigint;
  next_status text;
begin
  foreach vid in array array[
    case when tg_op <> 'INSERT' then old.vehicle_id end,
    case when tg_op <> 'DELETE' then new.vehicle_id end
  ] loop
    continue when vid is null;
    next_status := case when exists (
      select 1 from public.missions m where m.vehicle_id = vid and m.status = 'Ongoing'
    ) then 'Working' else 'Available' end;
    update public.vehicles set status = next_status
      where id = vid and status <> 'Under Maintenance' and status <> next_status;
  end loop;
  return null;
end $$;

create trigger missions_vehicle_status
  after insert or update of status, vehicle_id or delete on public.missions
  for each row execute function public.sync_vehicle_status();

-- ============ Reports ============
-- Profit = mission revenue − fuel − maintenance − expenses. Cancelled missions are not revenue.
create function public.vehicle_report(p_from date default null, p_to date default null, p_vehicle bigint default null)
returns table (id bigint, name text, plate text, ownership text, status text, missions bigint,
  revenue numeric, fuel numeric, liters numeric, maintenance numeric, expenses numeric, profit numeric)
language sql stable set search_path = '' as $$
  select x.*, x.revenue - x.fuel - x.maintenance - x.expenses as profit
  from (
    select v.id, v.name, v.plate, v.ownership, v.status,
      (select count(*) from public.missions m where m.vehicle_id = v.id and m.status <> 'Cancelled'
        and m.start_date between coalesce(p_from, '0001-01-01') and coalesce(p_to, '9999-12-31')),
      (select coalesce(sum(m.amount), 0) from public.missions m where m.vehicle_id = v.id and m.status <> 'Cancelled'
        and m.start_date between coalesce(p_from, '0001-01-01') and coalesce(p_to, '9999-12-31')),
      (select coalesce(sum(f.cost), 0) from public.fuel f where f.vehicle_id = v.id
        and f.date between coalesce(p_from, '0001-01-01') and coalesce(p_to, '9999-12-31')),
      (select coalesce(sum(f.liters), 0) from public.fuel f where f.vehicle_id = v.id
        and f.date between coalesce(p_from, '0001-01-01') and coalesce(p_to, '9999-12-31')),
      (select coalesce(sum(r.cost), 0) from public.maintenance r where r.vehicle_id = v.id
        and r.date between coalesce(p_from, '0001-01-01') and coalesce(p_to, '9999-12-31')),
      (select coalesce(sum(e.amount), 0) from public.expenses e where e.vehicle_id = v.id
        and e.date between coalesce(p_from, '0001-01-01') and coalesce(p_to, '9999-12-31'))
    from public.vehicles v
    where p_vehicle is null or v.id = p_vehicle
  ) x (id, name, plate, ownership, status, missions, revenue, fuel, liters, maintenance, expenses)
  order by x.name
$$;

create function public.client_report(p_from date default null, p_to date default null, p_client bigint default null)
returns table (id bigint, name text, type text, missions bigint, billed numeric, received numeric, balance numeric)
language sql stable set search_path = '' as $$
  select x.*, x.billed - x.received as balance
  from (
    select c.id, c.name, c.type,
      (select count(*) from public.missions m where m.client_id = c.id and m.status <> 'Cancelled'
        and m.start_date between coalesce(p_from, '0001-01-01') and coalesce(p_to, '9999-12-31')),
      (select coalesce(sum(m.amount), 0) from public.missions m where m.client_id = c.id and m.status <> 'Cancelled'
        and m.start_date between coalesce(p_from, '0001-01-01') and coalesce(p_to, '9999-12-31')),
      (select coalesce(sum(p.amount), 0) from public.payments p where p.client_id = c.id
        and p.date between coalesce(p_from, '0001-01-01') and coalesce(p_to, '9999-12-31'))
    from public.clients c
    where p_client is null or c.id = p_client
  ) x (id, name, type, missions, billed, received)
  order by x.name
$$;

create function public.dashboard(p_from date default null, p_to date default null)
returns json
language sql stable set search_path = '' as $$
  with r as (select coalesce(p_from, '0001-01-01'::date) f, coalesce(p_to, '9999-12-31'::date) t)
  select json_build_object(
    'revenue', (select coalesce(sum(amount), 0) from public.missions, r where status <> 'Cancelled' and start_date between r.f and r.t),
    'fuel', (select coalesce(sum(cost), 0) from public.fuel, r where date between r.f and r.t),
    'maintenance', (select coalesce(sum(cost), 0) from public.maintenance, r where date between r.f and r.t),
    'expenses', (select coalesce(sum(amount), 0) from public.expenses, r where date between r.f and r.t),
    'received', (select coalesce(sum(amount), 0) from public.payments, r where date between r.f and r.t),
    'outstanding', (select coalesce(sum(amount), 0) from public.missions where status <> 'Cancelled')
                 - (select coalesce(sum(amount), 0) from public.payments),
    'vehicle_status', (select coalesce(json_object_agg(status, n), '{}') from (select status, count(*) n from public.vehicles group by status) s),
    'mission_status', (select coalesce(json_object_agg(status, n), '{}') from (select status, count(*) n from public.missions group by status) s),
    'monthly', (select json_agg(row_to_json(m) order by m.month) from (
      select to_char(d, 'YYYY-MM') as month,
        (select coalesce(sum(amount), 0) from public.missions where status <> 'Cancelled' and date_trunc('month', start_date) = d) as revenue,
        (select coalesce(sum(cost), 0) from public.fuel where date_trunc('month', date) = d)
          + (select coalesce(sum(cost), 0) from public.maintenance where date_trunc('month', date) = d)
          + (select coalesce(sum(amount), 0) from public.expenses where date_trunc('month', date) = d) as costs
      from generate_series(date_trunc('month', current_date) - interval '5 months', date_trunc('month', current_date), interval '1 month') d
    ) m)
  )
$$;

