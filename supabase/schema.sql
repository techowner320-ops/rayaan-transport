-- ============ Part 7: two-step sign-in that the database enforces ============
-- A session may read or change business data only after it has been "verified": either it signed in
-- with the password AND confirmed an emailed code, or verification is switched off in Settings.
create table public.login_gate (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('password', 'verified')),
  session_id text,
  used boolean not null default false,
  created_at timestamptz not null default now()
);
create index on public.login_gate (user_id, kind, created_at desc);
create index on public.login_gate (session_id) where kind = 'verified';
alter table public.login_gate enable row level security;   -- no policies: nobody reads it directly
revoke all on public.login_gate from anon, authenticated;

alter table public.settings add column require_login_code boolean not null default false;

create function public.session_verified() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.login_gate g
    where g.kind = 'verified' and g.user_id = auth.uid() and g.session_id = (auth.jwt() ->> 'session_id')
  )
$$;

create or replace function public.is_member() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((select p.role in ('staff', 'admin') from public.profiles p where p.id = auth.uid()), false)
    and public.session_verified()
$$;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((select p.role = 'admin' from public.profiles p where p.id = auth.uid()), false)
    and public.session_verified()
$$;

create function public.begin_login() returns json
language plpgsql security definer set search_path = '' as $$
declare need boolean;
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  select coalesce(s.require_login_code, false) into need from public.settings s where s.id = 1;
  delete from public.login_gate where created_at < now() - interval '90 days';
  if need then
    insert into public.login_gate (user_id, kind) values (auth.uid(), 'password');
  else
    insert into public.login_gate (user_id, kind, session_id) values (auth.uid(), 'verified', auth.jwt() ->> 'session_id');
  end if;
  return json_build_object('need_code', need);
end $$;

create function public.complete_login() returns boolean
language plpgsql security definer set search_path = '' as $$
declare gate_id bigint;
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  select g.id into gate_id from public.login_gate g
   where g.user_id = auth.uid() and g.kind = 'password' and not g.used and g.created_at > now() - interval '10 minutes'
   order by g.created_at desc limit 1 for update;
  if gate_id is null then raise exception 'Start again: sign in with your password first.'; end if;
  update public.login_gate set used = true where id = gate_id;
  insert into public.login_gate (user_id, kind, session_id) values (auth.uid(), 'verified', auth.jwt() ->> 'session_id');
  return true;
end $$;

create function public.carry_over_session(p_old text) returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  if not exists (select 1 from public.login_gate g where g.kind = 'verified' and g.user_id = auth.uid() and g.session_id = p_old) then
    raise exception 'This session could not be verified.';
  end if;
  insert into public.login_gate (user_id, kind, session_id)
    select auth.uid(), 'verified', auth.jwt() ->> 'session_id'
    where not exists (select 1 from public.login_gate g where g.kind = 'verified' and g.session_id = (auth.jwt() ->> 'session_id'));
  return true;
end $$;

revoke execute on function public.session_verified() from public, anon;
revoke execute on function public.begin_login() from public, anon;
revoke execute on function public.complete_login() from public, anon;
revoke execute on function public.carry_over_session(text) from public, anon;
grant execute on function public.session_verified() to authenticated;
grant execute on function public.begin_login() to authenticated;
grant execute on function public.complete_login() to authenticated;
grant execute on function public.carry_over_session(text) to authenticated;
